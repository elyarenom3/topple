"""Rigid body data model shared by physics, statics, planning, harness and render.

State per body (Section 4.1): rotation q (unit quaternion, world from body), centre of
mass position x, linear velocity v, angular velocity w (world frame). Body frames sit
at the centre of mass along the principal axes of inertia (Section 4.2), so the body
inertia is diagonal for stones generated by ``stonegen``.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np

from ..core.mesh import SDF, TriMesh, convex_pieces
from ..core.transforms import SE3, quat_normalize, quat_rotate, quat_to_rot


@dataclass
class CollisionShape:
    """Geometry of one body in its body frame."""

    mesh: TriMesh  # full surface mesh (body frame)
    pieces: list  # list[TriMesh] convex pieces (body frame), hull for nearly convex stones
    sdf: Optional[SDF] = None  # signed distance field (body frame), 1 mm by default
    bounding_radius: float = 0.0
    kind: str = "mesh"  # "mesh", "halfspace" (ground plane z = 0), "box"

    @staticmethod
    def from_mesh(mesh: TriMesh, sdf_spacing: float | None = 0.001, sdf_padding: float = 0.01) -> "CollisionShape":
        pieces = convex_pieces(mesh)
        sdf = SDF.from_mesh(mesh, sdf_spacing, sdf_padding) if sdf_spacing else None
        r = float(np.linalg.norm(mesh.vertices, axis=1).max())
        return CollisionShape(mesh=mesh, pieces=pieces, sdf=sdf, bounding_radius=r)

    @staticmethod
    def ground(size: float = 10.0) -> "CollisionShape":
        """Half space z <= 0 with a large plane mesh for rendering and ray casting."""
        from ..core.mesh import box

        m = box((size, size, 0.2), center=(0.0, 0.0, -0.1))
        return CollisionShape(mesh=m, pieces=[m], sdf=None, bounding_radius=size, kind="halfspace")


class RigidBody:
    """A rigid body with mass properties, pose and twist."""

    __slots__ = ("id", "name", "mass", "inertia_body", "q", "x", "v", "w", "shape", "friction", "static", "kinematic", "group", "meta", "_inv_I_body")

    def __init__(
        self,
        name: str,
        mass: float,
        inertia_body: np.ndarray,
        shape: CollisionShape,
        q=None,
        x=None,
        friction: float = 0.6,
        static: bool = False,
        kinematic: bool = False,
    ):
        self.id = -1
        self.name = name
        self.mass = float(mass)
        self.inertia_body = np.asarray(inertia_body, dtype=np.float64).reshape(3, 3)
        self.q = quat_normalize(np.array([1.0, 0.0, 0.0, 0.0]) if q is None else np.asarray(q, dtype=np.float64))
        self.x = np.zeros(3) if x is None else np.asarray(x, dtype=np.float64).copy()
        self.v = np.zeros(3)
        self.w = np.zeros(3)
        self.shape = shape
        self.friction = float(friction)
        self.static = bool(static)
        self.kinematic = bool(kinematic)  # prescribed velocity (arm links, fingers, shake table)
        self.group = -1  # merging group (Section 6.5), -1 = none
        self.meta: dict = {}
        self._inv_I_body = None

    # ---------------------------------------------------------------- helpers
    @staticmethod
    def from_mesh(name: str, mesh: TriMesh, density: float, friction: float = 0.6, sdf_spacing: float | None = 0.001, pose: SE3 | None = None) -> "RigidBody":
        """Build a body whose body frame is the principal frame of ``mesh``.

        ``mesh`` is given in some reference frame; the body frame is placed at the centre
        of mass along the principal axes and the stored shape is expressed there. If ``pose``
        is None the body is placed so that the mesh sits where it was given; otherwise the
        given mesh is moved by ``pose`` (body pose = pose composed with the principal frame).
        """
        body_mesh, frame = mesh.to_principal_frame(density)
        mp = body_mesh.mass_properties(density)
        shape = CollisionShape.from_mesh(body_mesh, sdf_spacing)
        b = RigidBody(name, mp["mass"], np.diag(np.diag(mp["inertia_com"])), shape, friction=friction)
        # ``pose`` moves the mesh as given, so the body pose is pose composed with the
        # principal frame of the mesh in its given coordinates
        T = frame if pose is None else pose.compose(frame)
        b.q = T.q.copy()
        b.x = T.t.copy()
        b.meta["density"] = density
        b.meta["volume"] = mp["volume"]
        return b

    @staticmethod
    def ground(friction: float = 0.6, size: float = 10.0) -> "RigidBody":
        b = RigidBody("ground", np.inf, np.diag([np.inf] * 3), CollisionShape.ground(size), friction=friction, static=True)
        return b

    @property
    def pose(self) -> SE3:
        return SE3(self.q, self.x)

    @pose.setter
    def pose(self, T: SE3):
        self.q = quat_normalize(T.q)
        self.x = np.asarray(T.t, dtype=np.float64).copy()

    @property
    def R(self) -> np.ndarray:
        return quat_to_rot(self.q)

    @property
    def inv_mass(self) -> float:
        return 0.0 if (self.static or self.kinematic or not np.isfinite(self.mass)) else 1.0 / self.mass

    def inertia_world(self) -> np.ndarray:
        R = self.R
        return R @ self.inertia_body @ R.T

    @property
    def inv_inertia_body(self) -> np.ndarray:
        if self._inv_I_body is None:
            self._inv_I_body = np.linalg.inv(self.inertia_body) if np.all(np.isfinite(self.inertia_body)) else np.zeros((3, 3))
        return self._inv_I_body

    def inv_inertia_world(self, R: np.ndarray | None = None) -> np.ndarray:
        if self.static or self.kinematic or not np.isfinite(self.mass):
            return np.zeros((3, 3))
        R = self.R if R is None else R
        return R @ self.inv_inertia_body @ R.T

    def world_mesh(self) -> TriMesh:
        return self.shape.mesh.transformed(self.pose)

    def world_pieces(self) -> list:
        T = self.pose
        return [p.transformed(T) for p in self.shape.pieces]

    def point_velocity(self, p_world: np.ndarray) -> np.ndarray:
        return self.v + np.cross(self.w, np.asarray(p_world) - self.x)

    def kinetic_energy(self) -> float:
        if not np.isfinite(self.mass):
            return 0.0
        return 0.5 * self.mass * float(self.v @ self.v) + 0.5 * float(self.w @ self.inertia_world() @ self.w)

    def copy(self) -> "RigidBody":
        b = RigidBody(self.name, self.mass, self.inertia_body.copy(), self.shape, self.q.copy(), self.x.copy(), self.friction, self.static, self.kinematic)
        b.id = self.id
        b.v = self.v.copy()
        b.w = self.w.copy()
        b.group = self.group
        b.meta = dict(self.meta)
        return b

    def __repr__(self) -> str:
        return f"RigidBody({self.name}, id={self.id}, m={self.mass:.4g}, x={np.round(self.x, 4).tolist()})"


@dataclass
class Contact:
    """One contact point between body_a and body_b.

    ``normal`` points from a towards b; the force applied on b is
    f = fn * normal + ft1 * t1 + ft2 * t2 and the opposite force acts on a.
    ``depth`` is positive when the bodies interpenetrate.
    """

    body_a: int
    body_b: int
    point: np.ndarray
    normal: np.ndarray
    depth: float
    t1: np.ndarray = field(default_factory=lambda: np.zeros(3))
    t2: np.ndarray = field(default_factory=lambda: np.zeros(3))
    mu: float = 0.6
    fn: float = 0.0  # normal impulse (physics) or force (statics)
    ft1: float = 0.0
    ft2: float = 0.0
    feature: int = -1  # id for warm starting

    def force(self) -> np.ndarray:
        return self.fn * self.normal + self.ft1 * self.t1 + self.ft2 * self.t2

    def utilisation(self) -> float:
        """Tangential force over its friction limit (Section 10.6, O1)."""
        if self.fn <= 0:
            return 0.0
        return float(np.hypot(self.ft1, self.ft2) / (self.mu * self.fn))


@dataclass
class WorldState:
    """Snapshot of all body states, used for cloning, recording and tests."""

    time: float
    q: np.ndarray  # (n, 4)
    x: np.ndarray  # (n, 3)
    v: np.ndarray  # (n, 3)
    w: np.ndarray  # (n, 3)

    def copy(self) -> "WorldState":
        return WorldState(self.time, self.q.copy(), self.x.copy(), self.v.copy(), self.w.copy())
